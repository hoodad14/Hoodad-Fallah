CREATE OR REPLACE FUNCTION support_cancel_reservation(
    p_support_user_id BIGINT,
    p_reservation_id BIGINT,
    p_reason TEXT
)
RETURNS TABLE (
    reservation_id BIGINT,
    reservation_status VARCHAR,
    released_quantity INTEGER
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_reservation RECORD;
BEGIN
    IF p_support_user_id IS NULL OR p_reservation_id IS NULL THEN
        RAISE EXCEPTION 'Support user and reservation are required.';
    END IF;
    IF p_reason IS NULL OR btrim(p_reason) = '' THEN
        RAISE EXCEPTION 'Cancellation reason is required.';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM users
        WHERE id = p_support_user_id AND role = 'support' AND is_active
    ) THEN
        RAISE EXCEPTION 'User % is not an active support user.', p_support_user_id;
    END IF;

    SELECT r.id, r.status, r.ticket_id, r.quantity, r.expires_at
    INTO v_reservation
    FROM reservations r
    WHERE r.id = p_reservation_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Reservation % does not exist.', p_reservation_id;
    END IF;

    IF v_reservation.status = 'paid' THEN
        RAISE EXCEPTION 'Paid reservations must use the cancellation/refund workflow.';
    END IF;
    IF v_reservation.status <> 'held' THEN
        RAISE EXCEPTION 'Reservation status % cannot be canceled by support.', v_reservation.status;
    END IF;

    PERFORM id FROM tickets WHERE id = v_reservation.ticket_id FOR UPDATE;
    PERFORM release_pending_seat_change_holds(
        p_reservation_id,
        'Destination hold released because support canceled the reservation'
    );

    UPDATE tickets
    SET held_quantity = held_quantity - v_reservation.quantity
    WHERE id = v_reservation.ticket_id
      AND held_quantity >= v_reservation.quantity;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Ticket held counter is inconsistent for reservation %.', p_reservation_id;
    END IF;

    UPDATE reservations
    SET status = 'canceled',
        canceled_at = CURRENT_TIMESTAMP,
        canceled_by = p_support_user_id,
        cancellation_reason = btrim(p_reason)
    WHERE id = p_reservation_id;

    RETURN QUERY
    SELECT p_reservation_id, 'canceled'::VARCHAR, v_reservation.quantity;
END;
$$;


