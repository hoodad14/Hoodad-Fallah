CREATE OR REPLACE FUNCTION trg_validate_support_conversation_users()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM users
        WHERE id=NEW.spectator_id AND role='spectator' AND is_active
    ) THEN
        RAISE EXCEPTION 'Conversation spectator % must be an active spectator.', NEW.spectator_id;
    END IF;
    IF NEW.assigned_to IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM users
        WHERE id=NEW.assigned_to AND role='support' AND is_active
    ) THEN
        RAISE EXCEPTION 'Assigned user % must be an active support user.', NEW.assigned_to;
    END IF;
    RETURN NEW;
END;
$$;

