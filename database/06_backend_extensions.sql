CREATE OR REPLACE FUNCTION enqueue_ticket_search_sync(p_ticket_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_ticket_id IS NULL OR p_ticket_id <= 0 THEN
        RETURN;
    END IF;
    INSERT INTO search_sync_outbox(ticket_id)
    VALUES (p_ticket_id)
    ON CONFLICT (ticket_id) WHERE processed_at IS NULL
    DO UPDATE SET
        revision=search_sync_outbox.revision+1,
        attempts=0,
        available_at=CURRENT_TIMESTAMP,
        locked_at=NULL,
        locked_by=NULL,
        last_error=NULL;
END;
$$;

CREATE OR REPLACE FUNCTION trg_search_sync_ticket()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        PERFORM enqueue_ticket_search_sync(OLD.id);
        RETURN OLD;
    END IF;
    IF TG_OP = 'UPDATE' AND OLD.id IS DISTINCT FROM NEW.id THEN
        PERFORM enqueue_ticket_search_sync(OLD.id);
    END IF;
    PERFORM enqueue_ticket_search_sync(NEW.id);
    RETURN NEW;
END;
$$;

