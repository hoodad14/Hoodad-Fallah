CREATE OR REPLACE FUNCTION trg_validate_support_message_sender()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_spectator_id BIGINT;
    v_role VARCHAR(20);
BEGIN
    SELECT spectator_id INTO v_spectator_id
    FROM support_conversations
    WHERE id=NEW.conversation_id;
    IF v_spectator_id IS NULL THEN
        RAISE EXCEPTION 'Support conversation % does not exist.', NEW.conversation_id;
    END IF;

    SELECT role INTO v_role FROM users WHERE id=NEW.sender_id AND is_active;
    IF v_role IS NULL THEN
        RAISE EXCEPTION 'Message sender % is not active.', NEW.sender_id;
    END IF;
    IF NEW.sender_id<>v_spectator_id AND v_role<>'support' THEN
        RAISE EXCEPTION 'Message sender must be the conversation spectator or a support user.';
    END IF;
    RETURN NEW;
END;
$$;

