CREATE OR REPLACE FUNCTION trg_search_sync_match()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_id BIGINT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        v_id := OLD.id;
    ELSE
        v_id := NEW.id;
    END IF;
    PERFORM enqueue_ticket_search_sync(t.id)
    FROM tickets t WHERE t.match_id=v_id;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

