CREATE OR REPLACE FUNCTION trg_validate_report_links()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_ru BIGINT; v_rt BIGINT; v_pr BIGINT;
BEGIN
    IF NEW.reservation_id IS NOT NULL THEN
        SELECT user_id,ticket_id INTO v_ru,v_rt FROM reservations WHERE id=NEW.reservation_id;
        IF NEW.reporter_id<>v_ru THEN RAISE EXCEPTION 'Reporter must own reservation.'; END IF;
        IF NEW.ticket_id IS NOT NULL AND NEW.ticket_id<>v_rt THEN RAISE EXCEPTION 'Report ticket does not match reservation.'; END IF;
    END IF;
    IF NEW.payment_id IS NOT NULL THEN
        SELECT reservation_id INTO v_pr FROM payments WHERE id=NEW.payment_id;
        IF NEW.reservation_id IS NOT NULL AND NEW.reservation_id<>v_pr THEN RAISE EXCEPTION 'Report payment does not match reservation.'; END IF;
        IF NEW.reservation_id IS NULL THEN
            SELECT user_id,ticket_id INTO v_ru,v_rt FROM reservations WHERE id=v_pr;
            IF NEW.reporter_id<>v_ru THEN RAISE EXCEPTION 'Reporter must own payment.'; END IF;
            IF NEW.ticket_id IS NOT NULL AND NEW.ticket_id<>v_rt THEN RAISE EXCEPTION 'Report ticket does not match payment.'; END IF;
        END IF;
    END IF;
    RETURN NEW;
END; $$;
