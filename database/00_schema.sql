CREATE OR REPLACE FUNCTION trg_validate_venue_capacity_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE rec RECORD;
BEGIN
    IF NEW.capacity < OLD.capacity THEN
        PERFORM 1 FROM matches WHERE venue_id = OLD.id ORDER BY id FOR UPDATE;
        FOR rec IN
            SELECT m.id, COALESCE(SUM(t.total_capacity),0) AS allocated
            FROM matches m LEFT JOIN tickets t ON t.match_id=m.id
            WHERE m.venue_id=OLD.id GROUP BY m.id
        LOOP
            IF rec.allocated > NEW.capacity THEN
                RAISE EXCEPTION 'Venue capacity % is below the % tickets allocated for match %.',
                    NEW.capacity, rec.allocated, rec.id;
            END IF;
        END LOOP;
    END IF;
    RETURN NEW;
END;
$$;

