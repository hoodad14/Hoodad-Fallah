CREATE TABLE provinces (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_provinces_name UNIQUE (name),
    CONSTRAINT chk_provinces_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE cities (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    province_id  BIGINT NOT NULL REFERENCES provinces(id) ON DELETE RESTRICT,
    name         VARCHAR(100) NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_cities_province_name UNIQUE (province_id, name),
    CONSTRAINT chk_cities_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE venues (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id     BIGINT NOT NULL REFERENCES cities(id) ON DELETE RESTRICT,
    name        VARCHAR(200) NOT NULL,
    address     TEXT,
    capacity    INTEGER NOT NULL,
    latitude    NUMERIC(9,6),
    longitude   NUMERIC(9,6),
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_venues_city_name UNIQUE (city_id, name),
    CONSTRAINT chk_venues_capacity CHECK (capacity > 0),
    CONSTRAINT chk_venues_latitude CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_venues_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    CONSTRAINT chk_venues_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id             BIGINT REFERENCES cities(id) ON DELETE SET NULL,
    first_name          VARCHAR(100) NOT NULL,
    last_name           VARCHAR(100) NOT NULL,
    email               CITEXT,
    phone               VARCHAR(20),
    password_hash       VARCHAR(255) NOT NULL,
    role                VARCHAR(20) NOT NULL DEFAULT 'spectator',
    date_of_birth       DATE,
    profile_picture_url TEXT,
    preferred_login     VARCHAR(10) NOT NULL DEFAULT 'email',
    is_active           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT uq_users_phone UNIQUE (phone),
    CONSTRAINT chk_users_role CHECK (role IN ('spectator', 'support')),
    CONSTRAINT chk_users_preferred_login CHECK (preferred_login IN ('email', 'phone')),
    CONSTRAINT chk_users_contact CHECK (email IS NOT NULL OR phone IS NOT NULL),
    CONSTRAINT chk_users_preferred_login_contact CHECK (
        (preferred_login = 'email' AND email IS NOT NULL)
        OR
        (preferred_login = 'phone' AND phone IS NOT NULL)
    ),
    CONSTRAINT chk_users_password_hash_not_blank CHECK (btrim(password_hash) <> ''),
    CONSTRAINT chk_users_email_format CHECK (
        email IS NULL OR email::TEXT ~* '^[A-Z0-9._%+\-]+@[A-Z0-9.\-]+\.[A-Z]{2,}$'
    ),
    CONSTRAINT chk_users_phone_format CHECK (
        phone IS NULL OR phone ~ '^\+?[0-9]{10,15}$'
    ),
    CONSTRAINT chk_users_names CHECK (btrim(first_name) <> '' AND btrim(last_name) <> ''),
    CONSTRAINT chk_users_birth_date_lower_bound CHECK (
        date_of_birth IS NULL OR date_of_birth >= DATE '1900-01-01'
    )
);

CREATE TABLE wallets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    balance     NUMERIC(14,2) NOT NULL DEFAULT 0,
    currency    CHAR(3) NOT NULL DEFAULT 'IRR',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_wallets_user UNIQUE (user_id),
    CONSTRAINT chk_wallets_balance CHECK (balance >= 0),
    CONSTRAINT chk_wallets_currency CHECK (currency ~ '^[A-Z]{3}$')
);

CREATE TABLE sport_types (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50) NOT NULL,
    name        VARCHAR(100) NOT NULL,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_sport_types_code UNIQUE (code),
    CONSTRAINT uq_sport_types_name UNIQUE (name),
    CONSTRAINT chk_sport_types_code CHECK (code ~ '^[a-z0-9_]+$'),
    CONSTRAINT chk_sport_types_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE teams (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport_type_id  BIGINT NOT NULL REFERENCES sport_types(id) ON DELETE RESTRICT,
    city_id        BIGINT REFERENCES cities(id) ON DELETE SET NULL,
    name           VARCHAR(200) NOT NULL,
    short_name     VARCHAR(50),
    is_active      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_teams_sport_name UNIQUE (sport_type_id, name),
    CONSTRAINT chk_teams_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE organizers (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(200) NOT NULL,
    support_email  CITEXT,
    support_phone  VARCHAR(20),
    is_active      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_organizers_name UNIQUE (name),
    CONSTRAINT uq_organizers_email UNIQUE (support_email),
    CONSTRAINT uq_organizers_phone UNIQUE (support_phone),
    CONSTRAINT chk_organizers_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT chk_organizers_contact CHECK (support_email IS NOT NULL OR support_phone IS NOT NULL),
    CONSTRAINT chk_organizers_email_format CHECK (
        support_email IS NULL OR support_email::TEXT ~* '^[A-Z0-9._%+\-]+@[A-Z0-9.\-]+\.[A-Z]{2,}$'
    ),
    CONSTRAINT chk_organizers_phone_format CHECK (
        support_phone IS NULL OR support_phone ~ '^\+?[0-9]{10,15}$'
    )
);

CREATE TABLE matches (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport_type_id  BIGINT NOT NULL REFERENCES sport_types(id) ON DELETE RESTRICT,
    home_team_id   BIGINT NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    away_team_id   BIGINT NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    venue_id       BIGINT NOT NULL REFERENCES venues(id) ON DELETE RESTRICT,
    organizer_id   BIGINT NOT NULL REFERENCES organizers(id) ON DELETE RESTRICT,
    tournament_name VARCHAR(200) NOT NULL,
    starts_at      TIMESTAMPTZ NOT NULL,
    ends_at        TIMESTAMPTZ,
    status         VARCHAR(20) NOT NULL DEFAULT 'scheduled',
    is_active      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_matches_different_teams CHECK (home_team_id <> away_team_id),
    CONSTRAINT chk_matches_time CHECK (ends_at IS NULL OR ends_at > starts_at),
    CONSTRAINT chk_matches_status CHECK (status IN ('scheduled', 'postponed', 'canceled', 'completed')),
    CONSTRAINT chk_matches_tournament_not_blank CHECK (btrim(tournament_name) <> '')
);

CREATE TABLE ticket_categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50) NOT NULL,
    name        VARCHAR(100) NOT NULL,
    sort_order  SMALLINT NOT NULL DEFAULT 0,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_ticket_categories_code UNIQUE (code),
    CONSTRAINT uq_ticket_categories_name UNIQUE (name),
    CONSTRAINT chk_ticket_categories_code CHECK (code ~ '^[a-z0-9_]+$'),
    CONSTRAINT chk_ticket_categories_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE tickets (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id           BIGINT NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    ticket_category_id BIGINT NOT NULL REFERENCES ticket_categories(id) ON DELETE RESTRICT,
    section_code       VARCHAR(50) NOT NULL,
    row_code           VARCHAR(50),
    seat_code          VARCHAR(50),
    is_numbered        BOOLEAN NOT NULL DEFAULT FALSE,
    price              NUMERIC(14,2) NOT NULL,
    total_capacity     INTEGER NOT NULL,
    held_quantity        INTEGER NOT NULL DEFAULT 0,
    sold_quantity        INTEGER NOT NULL DEFAULT 0,
    change_held_quantity INTEGER NOT NULL DEFAULT 0,
    available_quantity   INTEGER GENERATED ALWAYS AS
        (total_capacity - held_quantity - sold_quantity - change_held_quantity) STORED,
    sale_starts_at     TIMESTAMPTZ,
    sale_ends_at       TIMESTAMPTZ,
    is_active          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_tickets_price CHECK (price >= 0),
    CONSTRAINT chk_tickets_capacity CHECK (total_capacity > 0),
    CONSTRAINT chk_tickets_quantities CHECK (
        held_quantity >= 0 AND sold_quantity >= 0 AND change_held_quantity >= 0 AND
        held_quantity + sold_quantity + change_held_quantity <= total_capacity
    ),
    CONSTRAINT chk_tickets_numbered_shape CHECK (
        (is_numbered = FALSE AND row_code IS NULL AND seat_code IS NULL)
        OR
        (is_numbered = TRUE AND row_code IS NOT NULL AND seat_code IS NOT NULL AND total_capacity = 1)
    ),
    CONSTRAINT chk_tickets_sale_window CHECK (
        sale_ends_at IS NULL OR sale_starts_at IS NULL OR sale_ends_at > sale_starts_at
    ),
    CONSTRAINT chk_tickets_section_not_blank CHECK (btrim(section_code) <> '')
);

CREATE TABLE amenities (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50) NOT NULL,
    name        VARCHAR(100) NOT NULL,
    description TEXT,
    CONSTRAINT uq_amenities_code UNIQUE (code),
    CONSTRAINT uq_amenities_name UNIQUE (name),
    CONSTRAINT chk_amenities_code CHECK (code ~ '^[a-z0-9_]+$'),
    CONSTRAINT chk_amenities_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE ticket_amenities (
    ticket_id   BIGINT NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
    amenity_id  BIGINT NOT NULL REFERENCES amenities(id) ON DELETE RESTRICT,
    details     VARCHAR(255),
    PRIMARY KEY (ticket_id, amenity_id)
);

CREATE TABLE reservations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    ticket_id           BIGINT NOT NULL REFERENCES tickets(id) ON DELETE RESTRICT,
    status              VARCHAR(20) NOT NULL DEFAULT 'held',
    quantity            INTEGER NOT NULL DEFAULT 1,
    unit_price          NUMERIC(14,2) NOT NULL,
    total_amount        NUMERIC(16,2) GENERATED ALWAYS AS (quantity * unit_price) STORED,
    reserved_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at          TIMESTAMPTZ NOT NULL,
    paid_at             TIMESTAMPTZ,
    canceled_at         TIMESTAMPTZ,
    canceled_by         BIGINT REFERENCES users(id) ON DELETE SET NULL,
    cancellation_reason TEXT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_reservations_status CHECK (status IN ('held', 'paid', 'canceled', 'expired', 'refunded')),
    CONSTRAINT chk_reservations_quantity CHECK (quantity > 0),
    CONSTRAINT chk_reservations_unit_price CHECK (unit_price >= 0),
    CONSTRAINT chk_reservations_expiry CHECK (expires_at > reserved_at),
    CONSTRAINT chk_reservations_paid_at CHECK (paid_at IS NULL OR paid_at >= reserved_at),
    CONSTRAINT chk_reservations_canceled_at CHECK (canceled_at IS NULL OR canceled_at >= reserved_at),
    CONSTRAINT chk_reservations_lifecycle CHECK (
        (status = 'held'
            AND paid_at IS NULL AND canceled_at IS NULL AND canceled_by IS NULL
            AND cancellation_reason IS NULL)
        OR
        (status = 'paid'
            AND paid_at IS NOT NULL AND canceled_at IS NULL AND canceled_by IS NULL
            AND cancellation_reason IS NULL)
        OR
        (status = 'canceled'
            AND paid_at IS NULL AND canceled_at IS NOT NULL AND canceled_by IS NOT NULL
            AND cancellation_reason IS NOT NULL AND btrim(cancellation_reason) <> '')
        OR
        (status = 'expired'
            AND paid_at IS NULL AND canceled_at IS NOT NULL AND canceled_by IS NULL
            AND cancellation_reason IS NOT NULL AND btrim(cancellation_reason) <> '')
        OR
        (status = 'refunded'
            AND paid_at IS NOT NULL AND canceled_at IS NOT NULL AND canceled_at >= paid_at
            AND canceled_by IS NOT NULL
            AND cancellation_reason IS NOT NULL AND btrim(cancellation_reason) <> '')
    )
);

CREATE TABLE payment_methods (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50) NOT NULL,
    name        VARCHAR(100) NOT NULL,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_payment_methods_code UNIQUE (code),
    CONSTRAINT uq_payment_methods_name UNIQUE (name),
    CONSTRAINT chk_payment_methods_code CHECK (code ~ '^[a-z0-9_]+$')
);

CREATE TABLE payments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id    BIGINT NOT NULL REFERENCES reservations(id) ON DELETE RESTRICT,
    payment_method_id BIGINT NOT NULL REFERENCES payment_methods(id) ON DELETE RESTRICT,
    amount            NUMERIC(16,2) NOT NULL,
    status            VARCHAR(20) NOT NULL DEFAULT 'pending',
    transaction_ref   VARCHAR(100) NOT NULL,
    failure_reason    TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at           TIMESTAMPTZ,
    CONSTRAINT uq_payments_transaction_ref UNIQUE (transaction_ref),
    CONSTRAINT chk_payments_transaction_ref CHECK (btrim(transaction_ref) <> ''),
    CONSTRAINT chk_payments_amount CHECK (amount >= 0),
    CONSTRAINT chk_payments_status CHECK (status IN ('pending', 'successful', 'failed', 'canceled')),
    CONSTRAINT chk_payments_paid_at CHECK (
        (status = 'successful' AND paid_at IS NOT NULL)
        OR
        (status <> 'successful' AND paid_at IS NULL)
    ),
    CONSTRAINT chk_payments_failure_reason CHECK (
        (status = 'failed' AND failure_reason IS NOT NULL AND btrim(failure_reason) <> '')
        OR
        (status <> 'failed' AND failure_reason IS NULL)
    )
);

CREATE TABLE wallet_transactions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id       BIGINT NOT NULL REFERENCES wallets(id) ON DELETE RESTRICT,
    payment_id      BIGINT REFERENCES payments(id) ON DELETE RESTRICT,
    transaction_type VARCHAR(20) NOT NULL,
    amount          NUMERIC(16,2) NOT NULL,
    balance_after   NUMERIC(16,2) NOT NULL,
    reference_code  VARCHAR(100) NOT NULL,
    description     TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_wallet_transactions_reference UNIQUE (reference_code),
    CONSTRAINT chk_wallet_transactions_reference CHECK (btrim(reference_code) <> ''),
    CONSTRAINT chk_wallet_transactions_type CHECK (transaction_type IN ('top_up', 'purchase', 'refund', 'adjustment')),
    CONSTRAINT chk_wallet_transactions_amount CHECK (amount <> 0),
    CONSTRAINT chk_wallet_transactions_balance CHECK (balance_after >= 0)
);

CREATE TABLE cancellation_policies (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizer_id          BIGINT NOT NULL REFERENCES organizers(id) ON DELETE CASCADE,
    hours_before_match    INTEGER NOT NULL,
    penalty_percentage    NUMERIC(5,2) NOT NULL,
    description           VARCHAR(255),
    CONSTRAINT uq_cancellation_policy UNIQUE (organizer_id, hours_before_match),
    CONSTRAINT chk_cancellation_policy_hours CHECK (hours_before_match >= 0),
    CONSTRAINT chk_cancellation_policy_penalty CHECK (penalty_percentage BETWEEN 0 AND 100)
);

CREATE TABLE cancellation_requests (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id         BIGINT NOT NULL REFERENCES reservations(id) ON DELETE RESTRICT,
    requested_by           BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    reason                 TEXT NOT NULL,
    status                 VARCHAR(20) NOT NULL DEFAULT 'pending',
    estimated_penalty_pct  NUMERIC(5,2),
    estimated_refund       NUMERIC(16,2),
    reviewed_by            BIGINT REFERENCES users(id) ON DELETE SET NULL,
    review_note            TEXT,
    requested_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at            TIMESTAMPTZ,
    CONSTRAINT chk_cancellation_requests_status CHECK (status IN ('pending', 'approved', 'rejected', 'processed')),
    CONSTRAINT chk_cancellation_requests_reason CHECK (btrim(reason) <> ''),
    CONSTRAINT chk_cancellation_requests_penalty CHECK (
        estimated_penalty_pct IS NULL OR estimated_penalty_pct BETWEEN 0 AND 100
    ),
    CONSTRAINT chk_cancellation_requests_refund CHECK (estimated_refund IS NULL OR estimated_refund >= 0),
    CONSTRAINT chk_cancellation_requests_review_lifecycle CHECK (
        (status = 'pending' AND reviewed_by IS NULL AND reviewed_at IS NULL)
        OR
        (status IN ('approved', 'rejected', 'processed')
            AND reviewed_by IS NOT NULL
            AND reviewed_at IS NOT NULL
            AND reviewed_at >= requested_at)
    )
);

CREATE TABLE refunds (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cancellation_request_id  BIGINT NOT NULL REFERENCES cancellation_requests(id) ON DELETE RESTRICT,
    payment_id               BIGINT NOT NULL REFERENCES payments(id) ON DELETE RESTRICT,
    wallet_id                BIGINT NOT NULL REFERENCES wallets(id) ON DELETE RESTRICT,
    amount                   NUMERIC(16,2) NOT NULL,
    penalty_amount           NUMERIC(16,2) NOT NULL DEFAULT 0,
    status                   VARCHAR(20) NOT NULL DEFAULT 'pending',
    transaction_ref          VARCHAR(100) NOT NULL,
    created_at               TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at             TIMESTAMPTZ,
    CONSTRAINT uq_refunds_request UNIQUE (cancellation_request_id),
    CONSTRAINT uq_refunds_payment UNIQUE (payment_id),
    CONSTRAINT uq_refunds_transaction_ref UNIQUE (transaction_ref),
    CONSTRAINT chk_refunds_transaction_ref CHECK (btrim(transaction_ref) <> ''),
    CONSTRAINT chk_refunds_amount CHECK (amount >= 0),
    CONSTRAINT chk_refunds_penalty CHECK (penalty_amount >= 0),
    CONSTRAINT chk_refunds_status CHECK (status IN ('pending', 'completed', 'failed')),
    CONSTRAINT chk_refunds_completed_at CHECK (
        (status = 'completed' AND completed_at IS NOT NULL)
        OR
        (status <> 'completed' AND completed_at IS NULL)
    )
);

CREATE TABLE seat_change_requests (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id        BIGINT NOT NULL REFERENCES reservations(id) ON DELETE RESTRICT,
    requested_by          BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    old_ticket_id         BIGINT NOT NULL REFERENCES tickets(id) ON DELETE RESTRICT,
    requested_ticket_id   BIGINT NOT NULL REFERENCES tickets(id) ON DELETE RESTRICT,
    quantity              INTEGER NOT NULL,
    old_unit_price        NUMERIC(14,2) NOT NULL,
    new_unit_price        NUMERIC(14,2) NOT NULL,
    target_hold_expires_at TIMESTAMPTZ NOT NULL,
    status                VARCHAR(20) NOT NULL DEFAULT 'pending',
    reviewed_by           BIGINT REFERENCES users(id) ON DELETE SET NULL,
    review_note           TEXT,
    requested_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at           TIMESTAMPTZ,
    CONSTRAINT chk_seat_change_different_tickets CHECK (old_ticket_id <> requested_ticket_id),
    CONSTRAINT chk_seat_change_quantity CHECK (quantity > 0),
    CONSTRAINT chk_seat_change_prices CHECK (old_unit_price >= 0 AND new_unit_price >= 0),
    CONSTRAINT chk_seat_change_equal_price CHECK (old_unit_price = new_unit_price),
    CONSTRAINT chk_seat_change_hold_window CHECK (target_hold_expires_at > requested_at),
    CONSTRAINT chk_seat_change_status CHECK (status IN ('pending', 'rejected', 'processed', 'expired')),
    CONSTRAINT chk_seat_change_review_lifecycle CHECK (
        (status = 'pending' AND reviewed_by IS NULL AND reviewed_at IS NULL)
        OR
        (status IN ('rejected', 'processed')
            AND reviewed_by IS NOT NULL
            AND reviewed_at IS NOT NULL
            AND reviewed_at >= requested_at)
        OR
        (status = 'expired'
            AND reviewed_by IS NULL
            AND reviewed_at IS NOT NULL
            AND reviewed_at >= requested_at)
    )
);

CREATE TABLE issued_tickets (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id   BIGINT NOT NULL REFERENCES reservations(id) ON DELETE RESTRICT,
    ticket_number    UUID NOT NULL DEFAULT gen_random_uuid(),
    qr_token         UUID NOT NULL DEFAULT gen_random_uuid(),
    status           VARCHAR(20) NOT NULL DEFAULT 'active',
    issued_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    used_at          TIMESTAMPTZ,
    CONSTRAINT uq_issued_tickets_number UNIQUE (ticket_number),
    CONSTRAINT uq_issued_tickets_qr UNIQUE (qr_token),
    CONSTRAINT chk_issued_tickets_status CHECK (status IN ('active', 'used', 'canceled')),
    CONSTRAINT chk_issued_tickets_used_at CHECK (
        (status = 'used' AND used_at IS NOT NULL)
        OR
        (status <> 'used' AND used_at IS NULL)
    )
);

CREATE TABLE report_categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(50) NOT NULL,
    name        VARCHAR(150) NOT NULL,
    CONSTRAINT uq_report_categories_code UNIQUE (code),
    CONSTRAINT uq_report_categories_name UNIQUE (name),
    CONSTRAINT chk_report_categories_code CHECK (code ~ '^[a-z0-9_]+$'),
    CONSTRAINT chk_report_categories_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE reports (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    ticket_id       BIGINT REFERENCES tickets(id) ON DELETE SET NULL,
    reservation_id  BIGINT REFERENCES reservations(id) ON DELETE SET NULL,
    payment_id      BIGINT REFERENCES payments(id) ON DELETE RESTRICT,
    category_id     BIGINT NOT NULL REFERENCES report_categories(id) ON DELETE RESTRICT,
    subject         VARCHAR(200) NOT NULL,
    description     TEXT NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'pending',
    assigned_to     BIGINT REFERENCES users(id) ON DELETE SET NULL,
    support_response TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
