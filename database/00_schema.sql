CREATE OR REPLACE FUNCTION trg_assert_ticket_inventory_counters()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_ids BIGINT[];
    v_id BIGINT;
    v_actual_held BIGINT;
    v_actual_sold BIGINT;
    v_actual_change_held BIGINT;
    v_stored RECORD;
BEGIN
    IF TG_TABLE_NAME='tickets' THEN
        IF TG_OP='INSERT' THEN v_ids:=ARRAY[NEW.id];
        ELSIF TG_OP='DELETE' THEN v_ids:=ARRAY[OLD.id];
        ELSE v_ids:=ARRAY[OLD.id,NEW.id]; END IF;
    ELSIF TG_TABLE_NAME='reservations' THEN
        IF TG_OP='INSERT' THEN v_ids:=ARRAY[NEW.ticket_id];
        ELSIF TG_OP='DELETE' THEN v_ids:=ARRAY[OLD.ticket_id];
        ELSE v_ids:=ARRAY[OLD.ticket_id,NEW.ticket_id]; END IF;
    ELSIF TG_TABLE_NAME='seat_change_requests' THEN
        IF TG_OP='INSERT' THEN v_ids:=ARRAY[NEW.requested_ticket_id];
        ELSIF TG_OP='DELETE' THEN v_ids:=ARRAY[OLD.requested_ticket_id];
        ELSE v_ids:=ARRAY[OLD.requested_ticket_id,NEW.requested_ticket_id]; END IF;
    ELSE
        IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
    END IF;

    FOREACH v_id IN ARRAY v_ids LOOP
        CONTINUE WHEN v_id IS NULL;

        SELECT held_quantity,sold_quantity,change_held_quantity
        INTO v_stored
        FROM tickets
        WHERE id=v_id;
        CONTINUE WHEN NOT FOUND;

        SELECT
            COALESCE(SUM(quantity) FILTER (WHERE status='held'),0),
            COALESCE(SUM(quantity) FILTER (WHERE status='paid'),0)
        INTO v_actual_held,v_actual_sold
        FROM reservations
        WHERE ticket_id=v_id;

        SELECT COALESCE(SUM(quantity),0)
        INTO v_actual_change_held
        FROM seat_change_requests
        WHERE requested_ticket_id=v_id AND status='pending';

        IF v_stored.held_quantity<>v_actual_held
           OR v_stored.sold_quantity<>v_actual_sold
           OR v_stored.change_held_quantity<>v_actual_change_held THEN
            RAISE EXCEPTION 'Ticket % inventory mismatch. stored=(%,%,%), actual=(%,%,%).',
                v_id,
                v_stored.held_quantity,v_stored.sold_quantity,v_stored.change_held_quantity,
                v_actual_held,v_actual_sold,v_actual_change_held;
        END IF;
    END LOOP;

    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;

CREATE CONSTRAINT TRIGGER assert_ticket_inventory_from_tickets
AFTER INSERT OR UPDATE OR DELETE ON tickets
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION trg_assert_ticket_inventory_counters();

