CREATE OR REPLACE FUNCTION trg_assert_reservation_financial_lifecycle()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_ids BIGINT[];
    v_id BIGINT;
    v_res RECORD;
    v_success_count BIGINT;
    v_issued_count BIGINT;
    v_canceled_issued_count BIGINT;
    v_completed_refund_count BIGINT;
BEGIN
    IF TG_TABLE_NAME='reservations' THEN
        IF TG_OP='INSERT' THEN v_ids:=ARRAY[NEW.id];
        ELSIF TG_OP='DELETE' THEN v_ids:=ARRAY[OLD.id];
        ELSE v_ids:=ARRAY[OLD.id,NEW.id]; END IF;
    ELSIF TG_TABLE_NAME='payments' THEN
        IF TG_OP='INSERT' THEN v_ids:=ARRAY[NEW.reservation_id];
        ELSIF TG_OP='DELETE' THEN v_ids:=ARRAY[OLD.reservation_id];
        ELSE v_ids:=ARRAY[OLD.reservation_id,NEW.reservation_id]; END IF;
    ELSIF TG_TABLE_NAME='issued_tickets' THEN
        IF TG_OP='INSERT' THEN v_ids:=ARRAY[NEW.reservation_id];
        ELSIF TG_OP='DELETE' THEN v_ids:=ARRAY[OLD.reservation_id];
        ELSE v_ids:=ARRAY[OLD.reservation_id,NEW.reservation_id]; END IF;
    ELSIF TG_TABLE_NAME='refunds' THEN
        IF TG_OP<>'INSERT' THEN
            SELECT p.reservation_id INTO v_id FROM payments p WHERE p.id=OLD.payment_id;
            v_ids:=ARRAY[v_id];
        ELSE
            v_ids:=ARRAY[]::BIGINT[];
        END IF;
        IF TG_OP<>'DELETE' THEN
            SELECT p.reservation_id INTO v_id FROM payments p WHERE p.id=NEW.payment_id;
            v_ids:=array_append(v_ids,v_id);
        END IF;
    ELSE
        IF TG_OP='DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
    END IF;

    FOREACH v_id IN ARRAY v_ids LOOP
        CONTINUE WHEN v_id IS NULL;

        SELECT status,quantity
        INTO v_res
        FROM reservations
        WHERE id=v_id;
        CONTINUE WHEN NOT FOUND;

        SELECT COUNT(*)
        INTO v_success_count
        FROM payments
        WHERE reservation_id=v_id AND status='successful';

        SELECT COUNT(*),COUNT(*) FILTER (WHERE status='canceled')
        INTO v_issued_count,v_canceled_issued_count
        FROM issued_tickets
        WHERE reservation_id=v_id;

        SELECT COUNT(*)
        INTO v_completed_refund_count
        FROM refunds rf
        JOIN payments p ON p.id=rf.payment_id
        WHERE p.reservation_id=v_id AND rf.status='completed';

        IF v_res.status IN ('paid','refunded') THEN
            IF v_success_count<>1 THEN
                RAISE EXCEPTION 'Reservation % in status % must have exactly one successful payment.',v_id,v_res.status;
            END IF;
            IF v_issued_count<>v_res.quantity THEN
                RAISE EXCEPTION 'Reservation % must have % issued ticket rows, found %.',v_id,v_res.quantity,v_issued_count;
            END IF;
        ELSE
            IF v_success_count<>0 OR v_issued_count<>0 OR v_completed_refund_count<>0 THEN
                RAISE EXCEPTION 'Reservation % in status % cannot have successful payment, issued ticket or completed refund rows.',v_id,v_res.status;
            END IF;
        END IF;

        IF v_res.status='paid' THEN
            IF v_completed_refund_count<>0 OR v_canceled_issued_count<>0 THEN
                RAISE EXCEPTION 'Paid reservation % cannot have a completed refund or canceled issued tickets.',v_id;
            END IF;
        ELSIF v_res.status='refunded' THEN
            IF v_completed_refund_count<>1 OR v_canceled_issued_count<>v_res.quantity THEN
                RAISE EXCEPTION 'Refunded reservation % must have one completed refund and all issued tickets canceled.',v_id;
            END IF;
        END IF;
    END LOOP;

    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;

CREATE CONSTRAINT TRIGGER assert_financial_lifecycle_from_reservations
AFTER INSERT OR UPDATE OR DELETE ON reservations
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION trg_assert_reservation_financial_lifecycle();

