CREATE OR REPLACE FUNCTION trg_validate_status_transition()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_allowed BOOLEAN:=FALSE;
BEGIN
    IF NEW.status IS NOT DISTINCT FROM OLD.status THEN RETURN NEW; END IF;
    CASE TG_TABLE_NAME
      WHEN 'reservations' THEN v_allowed := (OLD.status='held' AND NEW.status IN ('paid','canceled','expired')) OR (OLD.status='paid' AND NEW.status='refunded');
      WHEN 'payments' THEN v_allowed := OLD.status='pending' AND NEW.status IN ('successful','failed','canceled');
      WHEN 'cancellation_requests' THEN v_allowed := (OLD.status='pending' AND NEW.status IN ('approved','rejected','processed')) OR (OLD.status='approved' AND NEW.status IN ('rejected','processed'));
      WHEN 'refunds' THEN v_allowed := OLD.status='pending' AND NEW.status IN ('completed','failed');
      WHEN 'seat_change_requests' THEN v_allowed := OLD.status='pending' AND NEW.status IN ('rejected','processed','expired');
      WHEN 'issued_tickets' THEN v_allowed := OLD.status='active' AND NEW.status IN ('used','canceled');
      WHEN 'reports' THEN v_allowed := (OLD.status='pending' AND NEW.status IN ('in_review','resolved','rejected')) OR (OLD.status='in_review' AND NEW.status IN ('resolved','rejected'));
      ELSE RETURN NEW;
    END CASE;
    IF NOT v_allowed THEN RAISE EXCEPTION 'Illegal status transition on %: % -> %.',TG_TABLE_NAME,OLD.status,NEW.status; END IF;
    RETURN NEW;
END; $$;
