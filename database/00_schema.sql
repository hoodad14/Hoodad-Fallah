CREATE OR REPLACE FUNCTION trg_assert_wallet_balance()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_ids BIGINT[];
    v_id BIGINT;
    v_balance NUMERIC(16,2);
    v_ledger NUMERIC(16,2);
BEGIN
    IF TG_TABLE_NAME='wallets' THEN
        IF TG_OP='INSERT' THEN v_ids:=ARRAY[NEW.id];
        ELSIF TG_OP='DELETE' THEN v_ids:=ARRAY[OLD.id];
        ELSE v_ids:=ARRAY[OLD.id,NEW.id]; END IF;
    ELSE
        IF TG_OP='INSERT' THEN v_ids:=ARRAY[NEW.wallet_id];
        ELSIF TG_OP='DELETE' THEN v_ids:=ARRAY[OLD.wallet_id];
        ELSE v_ids:=ARRAY[OLD.wallet_id,NEW.wallet_id]; END IF;
    END IF;

    FOREACH v_id IN ARRAY v_ids LOOP
        CONTINUE WHEN v_id IS NULL;
        SELECT balance INTO v_balance FROM wallets WHERE id=v_id;
        CONTINUE WHEN NOT FOUND;
        SELECT COALESCE(SUM(amount),0) INTO v_ledger
        FROM wallet_transactions WHERE wallet_id=v_id;
        IF v_balance<>v_ledger THEN
            RAISE EXCEPTION 'Wallet % balance % does not equal ledger total %.',v_id,v_balance,v_ledger;
        END IF;
    END LOOP;

    IF TG_OP='DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;

CREATE CONSTRAINT TRIGGER assert_wallet_balance_from_wallets
AFTER INSERT OR UPDATE OR DELETE ON wallets
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION trg_assert_wallet_balance();

