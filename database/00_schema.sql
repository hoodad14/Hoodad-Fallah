CREATE OR REPLACE FUNCTION trg_validate_seat_change_request_links()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_owner   BIGINT;
    v_current BIGINT;
    v_qty     INTEGER;
    v_price   NUMERIC(14,2);
    v_old     RECORD;
    v_new     RECORD;
    v_definition_changed BOOLEAN;
BEGIN
    SELECT user_id,ticket_id,quantity,unit_price
    INTO v_owner,v_current,v_qty,v_price
    FROM reservations
    WHERE id=NEW.reservation_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Reservation % does not exist.', NEW.reservation_id;
    END IF;
    IF NEW.requested_by<>v_owner THEN
        RAISE EXCEPTION 'Seat-change requester must own reservation.';
    END IF;

    SELECT match_id,price,is_numbered,total_capacity
    INTO v_old
    FROM tickets WHERE id=NEW.old_ticket_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Old ticket % does not exist.', NEW.old_ticket_id;
    END IF;

    SELECT match_id,price,is_numbered,total_capacity
    INTO v_new
    FROM tickets WHERE id=NEW.requested_ticket_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Requested ticket % does not exist.', NEW.requested_ticket_id;
    END IF;

    v_definition_changed := TG_OP='INSERT';
    IF TG_OP='UPDATE' THEN
        v_definition_changed :=
            NEW.reservation_id IS DISTINCT FROM OLD.reservation_id OR
            NEW.requested_by IS DISTINCT FROM OLD.requested_by OR
            NEW.old_ticket_id IS DISTINCT FROM OLD.old_ticket_id OR
            NEW.requested_ticket_id IS DISTINCT FROM OLD.requested_ticket_id OR
            NEW.quantity IS DISTINCT FROM OLD.quantity OR
            NEW.old_unit_price IS DISTINCT FROM OLD.old_unit_price OR
            NEW.new_unit_price IS DISTINCT FROM OLD.new_unit_price;
    END IF;

    IF v_definition_changed THEN
        IF NEW.quantity<>v_qty THEN
            RAISE EXCEPTION 'Seat-change quantity must equal reservation quantity %.',v_qty;
        END IF;
        IF v_old.match_id<>v_new.match_id THEN
            RAISE EXCEPTION 'Seat/section changes must stay within the same match.';
        END IF;
        IF NEW.old_unit_price<>v_price
           OR NEW.new_unit_price<>v_new.price
           OR NEW.old_unit_price<>NEW.new_unit_price THEN
            RAISE EXCEPTION 'Seat/section changes require a same-price reservation snapshot.';
        END IF;
        IF v_new.is_numbered AND NEW.quantity<>1 THEN
            RAISE EXCEPTION 'A numbered destination seat requires quantity 1.';
        END IF;
    END IF;

    IF NEW.status='processed' AND v_current<>NEW.requested_ticket_id THEN
        RAISE EXCEPTION 'Processed seat change must point to reservation current ticket.';
    ELSIF NEW.status<>'processed' AND v_current<>NEW.old_ticket_id THEN
        RAISE EXCEPTION 'Unprocessed seat change must retain old ticket.';
    END IF;

    RETURN NEW;
END;
$$;

