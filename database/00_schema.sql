CREATE OR REPLACE FUNCTION trg_validate_ticket_capacity()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_venue_capacity INTEGER;
    v_match_starts   TIMESTAMPTZ;
    v_allocated      BIGINT;
BEGIN
    SELECT v.capacity, m.starts_at
    INTO v_venue_capacity, v_match_starts
    FROM matches m
    JOIN venues v ON v.id = m.venue_id
    WHERE m.id = NEW.match_id
    FOR UPDATE OF m;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Match % does not exist.', NEW.match_id;
    END IF;

    SELECT COALESCE(SUM(total_capacity), 0)
    INTO v_allocated
    FROM tickets
    WHERE match_id = NEW.match_id
      AND id <> COALESCE(NEW.id, -1);

    IF v_allocated + NEW.total_capacity > v_venue_capacity THEN
        RAISE EXCEPTION 'Allocated ticket capacity (%) exceeds venue capacity (%).',
            v_allocated + NEW.total_capacity, v_venue_capacity;
    END IF;

    IF NEW.sale_starts_at IS NOT NULL AND NEW.sale_starts_at >= v_match_starts THEN
        RAISE EXCEPTION 'Ticket sale must start before the match begins.';
    END IF;
    IF NEW.sale_ends_at IS NOT NULL AND NEW.sale_ends_at > v_match_starts THEN
        RAISE EXCEPTION 'Ticket sale cannot end after the match begins.';
    END IF;
    RETURN NEW;
END;
$$;

