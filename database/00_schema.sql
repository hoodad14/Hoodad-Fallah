CREATE OR REPLACE FUNCTION trg_validate_reservation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_ticket RECORD;
    v_user_role VARCHAR(20);
    v_user_active BOOLEAN;
BEGIN
    SELECT
        t.is_numbered,t.price,t.is_active AS ticket_active,
        t.sale_starts_at,t.sale_ends_at,
        m.status AS match_status,m.is_active AS match_active,m.starts_at,
        v.is_active AS venue_active,o.is_active AS organizer_active,
        st.is_active AS sport_active,ht.is_active AS home_team_active,
        at.is_active AS away_team_active,tc.is_active AS category_active
    INTO v_ticket
    FROM tickets t
    JOIN matches m ON m.id=t.match_id
    JOIN sport_types st ON st.id=m.sport_type_id
    JOIN teams ht ON ht.id=m.home_team_id
    JOIN teams at ON at.id=m.away_team_id
    JOIN venues v ON v.id=m.venue_id
    JOIN organizers o ON o.id=m.organizer_id
    JOIN ticket_categories tc ON tc.id=t.ticket_category_id
    WHERE t.id=NEW.ticket_id
    FOR SHARE OF t,m;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Ticket % does not exist.', NEW.ticket_id;
    END IF;
    IF v_ticket.is_numbered AND NEW.quantity <> 1 THEN
        RAISE EXCEPTION 'Numbered-seat tickets can only be reserved with quantity = 1.';
    END IF;
    IF NEW.unit_price <> v_ticket.price THEN
        RAISE EXCEPTION 'Reservation unit price % must equal current ticket price %.',
            NEW.unit_price, v_ticket.price;
    END IF;

    SELECT role,is_active
    INTO v_user_role,v_user_active
    FROM users
    WHERE id=NEW.user_id
    FOR SHARE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'User % does not exist.', NEW.user_id;
    END IF;
    IF v_user_role IS DISTINCT FROM 'spectator' THEN
        RAISE EXCEPTION 'Only spectator users may own reservations.';
    END IF;

    IF TG_OP='INSERT' THEN
        IF NOT v_user_active THEN
            RAISE EXCEPTION 'Inactive users cannot create reservations.';
        END IF;
    ELSIF NEW.user_id IS DISTINCT FROM OLD.user_id AND NOT v_user_active THEN
        RAISE EXCEPTION 'A reservation cannot be transferred to an inactive user.';
    END IF;

    IF TG_OP='INSERT' AND NEW.status='held' THEN
        IF NOT v_ticket.ticket_active OR NOT v_ticket.match_active
           OR NOT v_ticket.venue_active OR NOT v_ticket.organizer_active
           OR NOT v_ticket.sport_active OR NOT v_ticket.home_team_active
           OR NOT v_ticket.away_team_active OR NOT v_ticket.category_active
           OR v_ticket.match_status NOT IN ('scheduled','postponed')
           OR v_ticket.starts_at<=CURRENT_TIMESTAMP
           OR (v_ticket.sale_starts_at IS NOT NULL
               AND CURRENT_TIMESTAMP<v_ticket.sale_starts_at)
           OR (v_ticket.sale_ends_at IS NOT NULL
               AND CURRENT_TIMESTAMP>=v_ticket.sale_ends_at) THEN
            RAISE EXCEPTION 'A new hold must reference an active future sellable event.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

