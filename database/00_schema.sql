CREATE VIEW v_ticket_catalog AS
SELECT
    t.id AS ticket_id,
    m.id AS match_id,
    st.code AS sport_code,
    st.name AS sport_name,
    st.is_active AS sport_is_active,
    ht.name AS home_team,
    ht.is_active AS home_team_is_active,
    at.name AS away_team,
    at.is_active AS away_team_is_active,
    m.tournament_name,
    m.starts_at,
    m.ends_at,
    m.status AS match_status,
    m.is_active AS match_is_active,
    o.id AS organizer_id,
    o.name AS organizer_name,
    o.is_active AS organizer_is_active,
    v.id AS venue_id,
    v.name AS venue_name,
    v.is_active AS venue_is_active,
    c.id AS city_id,
    c.name AS city_name,
    p.name AS province_name,
    tc.code AS category_code,
    tc.name AS category_name,
    tc.is_active AS category_is_active,
    t.section_code,
    t.row_code,
    t.seat_code,
    t.is_numbered,
    t.price,
    t.total_capacity,
    t.held_quantity,
    t.sold_quantity,
    t.change_held_quantity,
    t.available_quantity,
    t.sale_starts_at,
    t.sale_ends_at,
    t.is_active,
    COALESCE(
        string_agg(DISTINCT a.name, ', ' ORDER BY a.name)
            FILTER (WHERE a.id IS NOT NULL),
        ''
    ) AS amenities
FROM tickets t
JOIN matches m ON m.id = t.match_id
JOIN sport_types st ON st.id = m.sport_type_id
JOIN teams ht ON ht.id = m.home_team_id
JOIN teams at ON at.id = m.away_team_id
JOIN organizers o ON o.id = m.organizer_id
JOIN venues v ON v.id = m.venue_id
JOIN cities c ON c.id = v.city_id
JOIN provinces p ON p.id = c.province_id
JOIN ticket_categories tc ON tc.id = t.ticket_category_id
LEFT JOIN ticket_amenities ta ON ta.ticket_id = t.id
LEFT JOIN amenities a ON a.id = ta.amenity_id
GROUP BY
    t.id, m.id, st.code, st.name, st.is_active,
    ht.name, ht.is_active, at.name, at.is_active, m.tournament_name,
    m.starts_at, m.ends_at, m.status, m.is_active,
    o.id, o.name, o.is_active,
    v.id, v.name, v.is_active, c.id, c.name, p.name,
    tc.code, tc.name, tc.is_active;

