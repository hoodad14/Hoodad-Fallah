CREATE OR REPLACE FUNCTION trg_validate_wallet_transaction_links()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_wallet_user    BIGINT;
    v_payment_user   BIGINT;
    v_status         VARCHAR(20);
    v_amount         NUMERIC(16,2);
    v_wallet_balance NUMERIC(16,2);
    v_ledger_before  NUMERIC(16,2);
    v_latest_entry   TIMESTAMPTZ;
BEGIN
    IF NEW.transaction_type IN ('purchase','refund') AND NEW.payment_id IS NULL THEN
        RAISE EXCEPTION '% wallet transactions must reference a payment.', NEW.transaction_type;
    ELSIF NEW.transaction_type IN ('top_up','adjustment') AND NEW.payment_id IS NOT NULL THEN
        RAISE EXCEPTION '% transaction cannot reference a payment.', NEW.transaction_type;
    END IF;

    SELECT user_id,balance
    INTO v_wallet_user,v_wallet_balance
    FROM wallets
    WHERE id=NEW.wallet_id
    FOR KEY SHARE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Wallet % does not exist.', NEW.wallet_id;
    END IF;

    SELECT COALESCE(SUM(amount),0),MAX(created_at)
    INTO v_ledger_before,v_latest_entry
    FROM wallet_transactions
    WHERE wallet_id=NEW.wallet_id;

    IF v_latest_entry IS NOT NULL AND NEW.created_at<v_latest_entry THEN
        RAISE EXCEPTION 'Wallet ledger entries must be appended chronologically.';
    END IF;

    IF NEW.balance_after <> v_wallet_balance
       OR NEW.balance_after <> v_ledger_before + NEW.amount THEN
        RAISE EXCEPTION 'Wallet ledger mismatch for wallet %: current balance %, previous ledger %, amount %, balance_after %.',
            NEW.wallet_id,v_wallet_balance,v_ledger_before,NEW.amount,NEW.balance_after;
    END IF;

    IF NEW.payment_id IS NOT NULL THEN
        SELECT r.user_id,p.status,p.amount
        INTO v_payment_user,v_status,v_amount
        FROM payments p
        JOIN reservations r ON r.id=p.reservation_id
        WHERE p.id=NEW.payment_id;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Payment % does not exist.', NEW.payment_id;
        END IF;
        IF v_wallet_user IS DISTINCT FROM v_payment_user THEN
            RAISE EXCEPTION 'Payment must belong to wallet owner.';
        END IF;
        IF v_status IS DISTINCT FROM 'successful' THEN
            RAISE EXCEPTION '% wallet transaction must reference a successful payment.',NEW.transaction_type;
        END IF;
        IF NEW.transaction_type='purchase' AND NEW.amount <> -v_amount THEN
            RAISE EXCEPTION 'Wallet purchase amount must equal negative payment amount.';
        END IF;
        IF NEW.transaction_type='refund' AND NOT EXISTS(
            SELECT 1
            FROM refunds rf
            WHERE rf.payment_id=NEW.payment_id
              AND rf.wallet_id=NEW.wallet_id
              AND rf.status='completed'
              AND rf.amount=NEW.amount
        ) THEN
            RAISE EXCEPTION 'Wallet refund must match a completed refund record.';
        END IF;
    END IF;

    IF NEW.transaction_type='purchase' AND NEW.amount>=0 THEN
        RAISE EXCEPTION 'Purchase amount must be negative.';
    ELSIF NEW.transaction_type IN ('top_up','refund') AND NEW.amount<=0 THEN
        RAISE EXCEPTION '% amount must be positive.',NEW.transaction_type;
    END IF;

    RETURN NEW;
END;
$$;

